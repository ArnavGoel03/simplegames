import { test } from "node:test";
import assert from "node:assert/strict";
import { latestDeployment, measuredValue, parseUploadedVersion, validateCandidate, validateCILookup, validateEvidence } from "./release-policy.mjs";

const head = "a".repeat(40);
const sha = "b".repeat(64);
const uuid = "12345678-1234-1234-1234-123456789abc";
const candidate = { schema: 1, kind: "candidate", site: "board", worker: "board", sourceHead: head, sourceFingerprint: sha, buildSource: sha, buildOutput: sha, candidateVersion: uuid, origin: "https://candidate.example.test", upload: { exitCode: 0, signal: null, logDigest: sha } };
const policy = { schema: 1, sites: { board: { checks: ["startup", "resize-play"], metrics: [{ id: "startup", unit: "ms", statistic: "median", minSamples: 3, limit: 200, baseline: { sourceHead: head, runId: 1, artifactId: 2, value: 100 } }] } } };
const report = () => ({ ...candidate, browsers: ["chromium", "webkit"].map((engine) => ({ engine, observedSourceHead: head, checks: [{ id: "startup", status: "passed" }, { id: "resize-play", status: "passed" }], measurements: [{ id: "startup", unit: "ms", samples: [90, 100, 110] }] })) });

test("computes measured statistics and accepts matching complete browser evidence", () => {
  assert.equal(measuredValue([6, 2, 4, 8], "median"), 5);
  assert.equal(measuredValue([6, 2, 4], "max"), 6);
  assert.equal(validateEvidence([report()], candidate, policy)[0].measurements[0].actual, 100);
  assert.doesNotThrow(() => validateCandidate(candidate, { site: "board", sourceHead: head }));
});

for (const [label, change] of [
  ["bare pass flag", (item) => { item.browsers = undefined; item.passed = true; }],
  ["missing WebKit", (item) => { item.browsers.pop(); }],
  ["duplicate engine", (item) => { item.browsers[1].engine = "chromium"; }],
  ["wrong source observed in HTML", (item) => { item.browsers[0].observedSourceHead = "c".repeat(40); }],
  ["wrong Worker version", (item) => { item.candidateVersion = "22345678-1234-1234-1234-123456789abc"; }],
  ["wrong source fingerprint", (item) => { item.sourceFingerprint = "c".repeat(64); }],
  ["wrong generated bytes", (item) => { item.buildOutput = "c".repeat(64); }],
  ["wrong preview", (item) => { item.origin = "https://other.example.test"; }],
  ["skipped check", (item) => { item.browsers[0].checks[0].status = "skipped"; }],
  ["failed check", (item) => { item.browsers[0].checks[0].status = "failed"; }],
  ["missing required check", (item) => { item.browsers[0].checks.pop(); }],
  ["duplicate check", (item) => { item.browsers[0].checks.push(item.browsers[0].checks[0]); }],
  ["over-budget measurement", (item) => { item.browsers[0].measurements[0].samples = [220, 230, 240]; }],
  ["invalid measurement", (item) => { item.browsers[0].measurements[0].samples[0] = null; }],
  ["insufficient measurements", (item) => { item.browsers[0].measurements[0].samples = [1]; }],
  ["wrong units", (item) => { item.browsers[0].measurements[0].unit = "seconds"; }],
]) test(`rejects ${label}`, () => { const item = report(); change(item); assert.throws(() => validateEvidence([item], candidate, policy)); });

test("refuses absent or invented policy baselines", () => {
  const missing = structuredClone(policy);
  missing.sites.board.metrics[0].baseline = undefined;
  assert.throws(() => validateEvidence([report()], candidate, missing), /baseline/);
  assert.throws(() => validateEvidence([report()], candidate, { schema: 1, sites: {} }), /no measured/);
  assert.throws(() => validateCandidate({ ...candidate, upload: { exitCode: 1 } }, {}), /upload/);
});

test("CI lookup requires the exact successful trusted manual workflow and artifact", () => {
  const ci = { repository: "owner/harness", workflow: ".github/workflows/visual.yml" };
  const run = { id: 1, status: "completed", conclusion: "success", event: "workflow_dispatch", repository: { full_name: ci.repository }, head_repository: { full_name: ci.repository }, path: ci.workflow, head_sha: head };
  const artifact = { id: 2, workflow_run: { id: 1 }, expired: false, digest: `sha256:${sha}`, size_in_bytes: 100 };
  assert.equal(validateCILookup(run, artifact, ci, 1, 2).workflowSourceHead, head);
  for (const change of [ { conclusion: "failure" }, { status: "in_progress" }, { event: "pull_request" }, { path: ".github/workflows/other.yml" }, { head_repository: { full_name: "fork/harness" } } ]) assert.throws(() => validateCILookup({ ...run, ...change }, artifact, ci, 1, 2));
  for (const change of [ { workflow_run: { id: 9 } }, { id: 9 }, { expired: true }, { digest: null }, { size_in_bytes: 65 * 1024 * 1024 } ]) assert.throws(() => validateCILookup(run, { ...artifact, ...change }, ci, 1, 2));
});

test("upload version parser rejects missing, malformed and ambiguous output", () => {
  assert.equal(parseUploadedVersion(`Uploaded worker\nWorker Version ID: ${uuid}\n`), uuid);
  for (const output of ["Uploaded worker", "Worker Version ID: invalid", `Worker Version ID: ${uuid}\nWorker Version ID: ${uuid}`]) assert.throws(() => parseUploadedVersion(output));
});

test("rollback selection uses provider timestamps, preserving the complete traffic split", () => {
  const old = { id: "old", created_on: "2026-09-12T00:00:00Z", versions: [{ version_id: uuid, percentage: 100 }] };
  const current = { id: "current", created_on: "2026-09-13T00:00:00Z", versions: [{ version_id: uuid, percentage: 25 }, { version_id: "22345678-1234-1234-1234-123456789abc", percentage: 75 }] };
  assert.equal(latestDeployment([current, old]).id, "current");
  assert.deepEqual(latestDeployment([old, current]).versions, current.versions);
  assert.throws(() => latestDeployment([]));
  assert.throws(() => latestDeployment([{ ...current, versions: [{ version_id: uuid, percentage: 40 }] }]));
});
